    void refresh() throws Exception {
        List<VRColumnTable> vColunaProduto = new ArrayList();
        vColunaProduto.add(new VRColumnTable("Código Ant.", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Código Class. Ant.", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm1 Ant", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm2 Ant", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm3 Ant.", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable(" - - ", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Cód. VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Cód. Class VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm1 VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm2 VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Ncm3 VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("ID Ncm VR", true, SwingConstants.CENTER, false, null));
        tblMapa.configurarColuna(vColunaProduto, this, "Mapa", "mapaClassificaçõesNcm");

        Object[][] dados = new Object[controller.getMapa().size()][tblMapa.getvColuna().size()];
        int i = 0;
        for (MapaReformaTributariaClassificacaoNcmVO classificacaoNcm : controller.getMapa()) {

            dados[i][0] = classificacaoNcm.getOrigId();
            dados[i][1] = classificacaoNcm.getOrigIdClassificacao();
            dados[i][2] = classificacaoNcm.getOrigNcm1();
            dados[i][3] = classificacaoNcm.getOrigNcm2();
            dados[i][4] = classificacaoNcm.getOrigNcm3();
            dados[i][5] = " >>>> ";
            if (classificacaoNcm.getClassificacaoNcm() == null) {
                dados[i][6] = "";
                dados[i][7] = "";
                dados[i][8] = "";
                dados[i][9] = "";
                dados[i][10] = "";
                dados[i][11] = "";
            } else {

                dados[i][6] = classificacaoNcm.getClassificacaoNcm().getId();
                dados[i][7] = classificacaoNcm.getClassificacaoNcm().getIdClassificacao();
                dados[i][8] = classificacaoNcm.getClassificacaoNcm().getNcm1();
                dados[i][9] = classificacaoNcm.getClassificacaoNcm().getNcm2();
                dados[i][10] = classificacaoNcm.getClassificacaoNcm().getNcm3();
                dados[i][11] = classificacaoNcm.getClassificacaoNcm().getIdNcm();
            }
            i++;
        }

        tblMapa.setModel(dados);
        tblMapa.setRowHeight(30);
        tblMapa.atualizarTamanhoColuna();
        if (tblMapa.getRowCount() > 0) {
            tblMapa.setLinhaSelecionada(0);
        }
    }

    void refreshBusca() throws Exception {
        List<VRColumnTable> vColunaProduto = new ArrayList();
        vColunaProduto.add(new VRColumnTable("ID NCM - VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("NCM 1 - VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("NCM 2 - VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("NCM 3 - VR", true, SwingConstants.CENTER, false, null));
        vColunaProduto.add(new VRColumnTable("Descricao", true, SwingConstants.LEFT, false, null));
        tblVR.configurarColuna(vColunaProduto, this, "NCM", "ncms");

        Object[][] dados = new Object[controller.getNcmsVR().size()][tblVR.getvColuna().size()];
        int i = 0;
        for (NcmVO ncm : controller.getNcmsVR()) {

            dados[i][0] = ncm.getId();
            dados[i][1] = ncm.getNcm1();
            dados[i][2] = ncm.getNcm2();
            dados[i][3] = ncm.getNcm3();
            dados[i][4] = ncm.getDescricao();

            i++;
        }

        tblVR.setModel(dados);
        tblVR.setRowHeight(30);
        tblVR.atualizarTamanhoColuna();
        if (tblVR.getRowCount() > 0) {
            tblVR.setLinhaSelecionada(0);
        }
    }
