    public static void exibir(Frame mdiFrame, String sistema, String loja, MapaReformaTributariaProvider provider, int lojaVR) throws Exception {
        MapaReformaTributariaClassificacaoNcmView view = new MapaReformaTributariaClassificacaoNcmView();
        view.setSistema(sistema);
        view.setLoja(loja);
        view.setProvider(provider);
        view.setMapaClassificacao();
        view.setLojaVR(lojaVR);

        view.controller.atualizarMapa();

        view.setPreferredSize(new Dimension(1200, 600));
        view.pack();

        Dimension ds = mdiFrame.getSize();
        Dimension dw = view.getSize();

        int x = (ds.width - dw.width) / 2;
        int y = (ds.height - dw.height) / 2;

        if (x < 0) {
            x = 0;
        }

        if (y < 0) {
            y = 0;
        }

        view.setLocation(x, y);
        view.setDefaultCloseOperation(WindowConstants.DISPOSE_ON_CLOSE);
        view.setVisible(true);
    }

