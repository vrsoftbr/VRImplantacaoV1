    private void pesquisar() {
        try {
            String ncm1 = classBuscaNcm1.getText().trim();
            String ncm2 = classBuscaNcm2.getText().trim();
            String ncm3 = classBuscaNcm3.getText().trim();

            if (ncm1.isEmpty() && ncm2.isEmpty() && ncm3.isEmpty()) {
                return;
            }

            controller.buscar(ncm1, ncm2, ncm3);

        } catch (Exception ex) {
            Exceptions.printStackTrace(ex);
            Util.exibirMensagemErro(ex, "Erro ao fazer a pesquisa de Classificações no VR");
        }
    }

